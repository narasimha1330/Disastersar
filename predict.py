import argparse
from pathlib import Path

import cv2
import joblib
import numpy as np
from tensorflow import keras


IMAGE_SIZE = (128, 128)
MODEL_FILES = {
    "svm": "svm_model.joblib",
    "random-forest": "random_forest_model.joblib",
    "decision-tree": "decision_tree_model.joblib",
}


def load_image(image_path: str) -> np.ndarray:
    """Read, resize, convert, and normalize one input image."""
    path = Path(image_path)
    if not path.is_file():
        raise FileNotFoundError(f"Image not found: {path.resolve()}")

    image = cv2.imread(str(path))
    if image is None:
        raise ValueError(f"Could not read image: {path.resolve()}")

    image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)
    image = cv2.resize(image, IMAGE_SIZE)
    return np.asarray(image, dtype=np.float32)[None, ...] / 255.0


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Classify a disaster-scene image as Body, Hand, or Leg."
    )
    parser.add_argument("--image", required=True, help="Path to the input image.")
    parser.add_argument(
        "--model",
        choices=MODEL_FILES,
        default="svm",
        help="Classifier to use (default: svm).",
    )
    parser.add_argument(
        "--artifacts",
        default="artifacts",
        help="Directory containing files generated by train.py.",
    )
    args = parser.parse_args()

    artifacts = Path(args.artifacts)
    extractor_path = artifacts / "cnn_feature_extractor.keras"
    encoder_path = artifacts / "label_encoder.joblib"
    classifier_path = artifacts / MODEL_FILES[args.model]

    for path in (extractor_path, encoder_path, classifier_path):
        if not path.is_file():
            raise FileNotFoundError(
                f"Required model file is missing: {path}. "
                "Run train.py successfully before prediction."
            )

    extractor = keras.models.load_model(extractor_path)
    encoder = joblib.load(encoder_path)
    classifier = joblib.load(classifier_path)

    features = extractor.predict(load_image(args.image), verbose=0)
    prediction = classifier.predict(features)
    label = encoder.inverse_transform(prediction.astype(int))[0]
    print(f"Predicted class: {label}")

    if hasattr(classifier, "predict_proba"):
        probabilities = classifier.predict_proba(features)[0]
        print("Class probabilities:")
        for class_name, probability in zip(encoder.classes_, probabilities):
            print(f"  {class_name}: {probability:.4f}")

    print(
        "Note: this educational image-classification result does not confirm "
        "that a living victim has been found."
    )


if __name__ == "__main__":
    main()
